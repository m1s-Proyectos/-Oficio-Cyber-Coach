import type { ScenarioDefinition, ScenarioNode, ScenarioOption } from '../../engine';
import { scoreForWhatsAppOption } from './scoring';

export const WHATSAPP_FAMILIAR_SLUG = 'whatsapp-familiar';

export const WHATSAPP_FAMILIAR_FICTION_NOTICE =
  'Esta historia es un ejercicio ficticio. Los nombres, importes, mensajes y desenlaces son parte del entrenamiento. No describen un caso real ni predicen cómo ocurren todos los fraudes.';

function option(
  id: string,
  label: string,
  nextNodeId: string,
  recognizedSignalIds: readonly string[],
  overlookedSignalIds: readonly string[],
  leavesRoomToCorrect: boolean,
  explanation: string,
  recommendation: string,
): ScenarioOption {
  const scored = scoreForWhatsAppOption(id);
  return {
    id,
    label,
    nextNodeId,
    evaluation: {
      points: scored.points,
      recognizedSignalIds,
      overlookedSignalIds,
      leavesRoomToCorrect,
      ...(scored.milestoneId !== undefined ? { milestoneId: scored.milestoneId } : {}),
    },
    feedback: { explanation, recommendation },
  };
}

function node(
  id: string,
  situation: string,
  prompt: string,
  isTerminal: boolean,
  visibleSignalIds: readonly string[],
  options: readonly ScenarioOption[],
): ScenarioNode {
  return { id, situation, prompt, isTerminal, visibleSignalIds, options };
}

